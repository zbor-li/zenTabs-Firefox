export type MessageKey = keyof typeof messages.en;

export function getLanguage(language?: Language): Language {
  return language === 'en' ? 'en' : 'zh';
}

export function t(language: Language | undefined, key: MessageKey, values?: Record<string, string>): string {
  let message: string = messages[getLanguage(language)][key];
  for (const [name, value] of Object.entries(values ?? {})) {
    message = message.replace(`{${name}}`, value);
  }
  return message;
}
